    <h2>Cómo Gestionar las Cookies</h2>
    <p>Al acceder a nuestro sitio web por primera vez, se le presentará un banner de cookies que le permitirá aceptar o rechazar las cookies no esenciales. Usted puede gestionar sus preferencias de cookies en cualquier momento:</p>
    <h3>Desde su navegador</h3>
    <p>La mayoría de los navegadores web le permiten ver, gestionar, eliminar y bloquear cookies. Puede configurar su navegador para:</p>
    <ul>
      <li>Ver y eliminar las cookies que ha almacenado.</li>
      <li>Bloquear todas las cookies o solo las cookies de terceros.</li>
      <li>Recibir una notificación cada vez que se instale una cookie.</li>
    </ul>
    <p>Si decide bloquear todas las cookies, es posible que no pueda acceder a ciertas funcionalidades del sitio, como el carrito de compras o iniciar sesión.</p>

    <h3>Desde nuestro sitio web</h3>
    <p>En cualquier momento, puede modificar sus preferencias de cookies haciendo clic en el enlace "Administrar Cookies" disponible en el pie de página de nuestro sitio web.</p>

