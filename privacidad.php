    En SERVIFARMACIA RK (<strong>en adelante, "la Farmacia", "nosotros", "nosotras" o "nuestra"</strong>), nos comprometemos a proteger la privacidad y seguridad de los datos personales de nuestros clientes y visitantes. Esta Política de Privacidad describe cómo recopilamos, utilizamos, compartimos y protegemos la información personal que usted nos proporcione a través de nuestro sitio web <strong>servifarmaciark.onrender.com</strong>, aplicaciones móviles y demás canales digitales.
