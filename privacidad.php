    <h2>6. Retención de Datos Personales</h2>
    <p>Conservamos la información personal durante el tiempo necesario para cumplir con las finalidades descritas en esta Política, o durante el tiempo que usted mantenga una cuenta en nuestro sitio, lo que ocurra primero. Específicamente:</p>
    <ul>
      <li><strong>Datos de cuenta:</strong> mientras su cuenta esté activa o hasta que solicite su eliminación.</li>
      <li><strong>Datos de pedidos y transacciones:</strong> durante un mínimo de 5 años, conforme a las obligaciones fiscales en Colombia.</li>
      <li><strong>Datos de navegación y cookies:</strong> durante 1 año a partir de su recopilación.</li>
    </ul>
    <p>Una vez finalizado el perioodo de retención, se eliminan o anonimizan sus datos personales de forma segura.</p>
