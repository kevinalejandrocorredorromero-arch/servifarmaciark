  <div class="section">
    <h2>1. Información Personal que Recopilamos</h2>
    <p>La información personal que usted nos proporciona activamente incluye, según corresponda:</p>
    <ul>
      <li><strong>Datos de identificación y contacto:</strong> nombre completo, dirección de correo electrónico, número de teléfono móvil, dirección de entrega y fecha de nacimiento.</li>
      <li><strong>Datos de registro de cuenta:</strong> nombre de usuario, contraseña y token de autenticación (almacenados de forma segura con hash).</li>
      <li><strong>Datos de pedidos y transacciones:</strong> información sobre los productos adquiridos, número de orden, detalles de entrega, método de pago seleccionado y comprobantes de pago.</li>
      <li><strong>Datos de comunicación:</strong> mensajes, consultas y reclamos que nos envía a través de chat en vivo, WhatsApp, correo electrónico u otros canales.</li>
    </ul>

    <h3>2.1 Información recopilada automáticamente</h3>
    <p>Al navegar por nuestro sitio web, también recopilamos cierta información de forma automática:</p>
    <ul>
      <li><strong>Datos de dispositivo y conexión:</strong> dirección IP, tipo y versión del navegador, sistema operativo, tipo de dispositivo, resolución de pantalla, proveedor de servicios de internet.</li>
      <li><strong>Datos de navegación:</strong> páginas o secciones visitadas, tiempo de permanencia, enlaces de origen, interacciones con funcionalidades y anuncios.</li>
      <li><strong>Datos de uso de la chat de IA:</strong> si utiliza nuestro asistente de chat basado en inteligencia artificial, recopilamos el historial de conversaciones y prompts para brindarle un servicio personalizado. Esta información puede incluir preguntas sobre productos farmacéuticos y recomendaciones.</li>
    </ul>

    <h3>2.2 Información de terceros</h3>
    <p>En los siguientes casos, también podemos recopilar información de terceros:</p>
    <ul>
      <li><strong>Proveedores de pasarela de pago:</strong> en caso de utilizar métodos de pago digital (Nequi, Daviplata), los datos de la transacción son procesados directamente por dichas plataformas, las cuales tienen sus propias políticas de privacidad.</li>
      <li><strong>Proveedores de envío y logística:</strong> compartimos la información de entrega necesaria para coordinar la entrega de su pedido.</li>
    </ul>
  </div>

