    <ul>
      <li><strong>Proveedores de servicios:</strong> plataformas de pasarela de pago (Nequi, Daviplata), proveedores de mensajería y logística, servicios de hosting y correo electrónico, y proveedores de análisis web.</li>
      <li><strong>Autoridades y organismos reguladores:</strong> cuando sea requerido por ley, normativa aplicable o procesos judiciales.</li>
      <li><strong>Para fines de prevención de fraude y seguridad:</strong> compartimos información con redes de prevención de fraudes y operadores de pagos para proteger nuestros servicios.</li>
